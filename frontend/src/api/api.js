/**
 * TalentLens Frontend API Client
 * Provides functions for interacting with backend endpoints and AWS S3 direct uploads.
 */

const API_BASE = import.meta.env.VITE_API_URL || '/api';

/**
 * Transform snake_case matchResult keys from the backend API to camelCase
 * used by React components.
 * @param {Object} candidate - Raw candidate object from API
 * @returns {Object} Candidate with camelCase matchResult keys
 */
function transformCandidate(candidate) {
  if (!candidate) return candidate;

  const result = { ...candidate };

  // Transform matchResult keys from snake_case to camelCase
  if (result.matchResult) {
    const mr = result.matchResult;
    result.matchResult = {
      matchPercentage: mr.match_percentage ?? mr.matchPercentage ?? 0,
      matchedSkills: mr.matched_skills ?? mr.matchedSkills ?? [],
      missingSkills: mr.missing_skills ?? mr.missingSkills ?? [],
      resumeSkills: mr.resume_skills ?? mr.resumeSkills ?? [],
      requiredSkills: mr.required_skills ?? mr.requiredSkills ?? [],
    };
  }

  return result;
}

/**
 * Parse API response body, handling both direct JSON and wrapped {body: string} patterns.
 * @param {Response} response - Fetch Response object
 * @returns {Promise<any>} Parsed data
 */
async function parseResponse(response) {
  const data = await response.json();
  // API Gateway proxy responses may wrap in { body: "..." }
  if (data && typeof data.body === 'string') {
    try {
      return JSON.parse(data.body);
    } catch (_) {
      return data;
    }
  }
  return data;
}

/**
 * Fetch a presigned S3 upload URL for a resume file.
 * @param {string} filename - Name of the file being uploaded
 * @returns {Promise<{ candidateId: string, uploadUrl: string, s3Key: string }>}
 */
export async function getPresignedUrl(filename) {
  if (!filename) {
    throw new Error('Filename is required to request an upload URL.');
  }

  try {
    const encodedFilename = encodeURIComponent(filename);
    const response = await fetch(`${API_BASE}/upload?filename=${encodedFilename}`, {
      method: 'GET',
      headers: {
        'Accept': 'application/json',
      },
    });

    if (!response.ok) {
      let errorMessage = `Failed to get presigned URL (Status: ${response.status})`;
      try {
        const errorData = await response.json();
        if (errorData?.message || errorData?.error) errorMessage = errorData.message || errorData.error;
      } catch (_) {
        if (response.statusText) errorMessage += `: ${response.statusText}`;
      }
      throw new Error(errorMessage);
    }

    const data = await parseResponse(response);
    return data;
  } catch (error) {
    console.error('getPresignedUrl error:', error);
    throw error instanceof Error ? error : new Error(String(error));
  }
}

/**
 * Upload a file directly to AWS S3 using the presigned PUT URL.
 * @param {string} presignedUrl - The presigned PUT URL generated by the backend
 * @param {File|Blob} file - The file content
 * @returns {Promise<boolean>}
 */
export async function uploadToS3(presignedUrl, file) {
  if (!presignedUrl) {
    throw new Error('Presigned upload URL is required.');
  }
  if (!file) {
    throw new Error('File payload is required.');
  }

  try {
    const response = await fetch(presignedUrl, {
      method: 'PUT',
      headers: {
        'Content-Type': 'application/pdf',
      },
      body: file,
    });

    if (!response.ok) {
      throw new Error(`S3 direct upload failed with status ${response.status}: ${response.statusText}`);
    }

    return true;
  } catch (error) {
    console.error('uploadToS3 error:', error);
    throw error instanceof Error ? error : new Error(String(error));
  }
}

/**
 * Report a failed upload to the backend so the candidate record is marked FAILED.
 * @param {string} candidateId - ID of the candidate
 * @param {string} errorMessage - Error description
 * @returns {Promise<any>}
 */
export async function reportUploadFailure(candidateId, errorMessage) {
  if (!candidateId) return null;
  try {
    const response = await fetch(`${API_BASE}/upload`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        candidateId,
        status: 'FAILED',
        errorMessage: errorMessage || 'Upload failed',
      }),
    });
    return await parseResponse(response);
  } catch (err) {
    console.error('reportUploadFailure error:', err);
    return null;
  }
}

/**
 * Fetch all processed and in-progress candidates.
 * @returns {Promise<Array>} Array of candidate objects
 */
export async function getCandidates() {
  try {
    const response = await fetch(`${API_BASE}/candidates`, {
      method: 'GET',
      headers: {
        'Accept': 'application/json',
      },
    });

    if (!response.ok) {
      let errorMessage = `Failed to fetch candidates (Status: ${response.status})`;
      try {
        const errorData = await response.json();
        if (errorData?.message || errorData?.error) errorMessage = errorData.message || errorData.error;
      } catch (_) {
        if (response.statusText) errorMessage += `: ${response.statusText}`;
      }
      throw new Error(errorMessage);
    }

    const data = await parseResponse(response);
    const candidates = Array.isArray(data) ? data : (data.candidates || []);
    return candidates.map(transformCandidate);
  } catch (error) {
    console.error('getCandidates error:', error);
    throw error instanceof Error ? error : new Error(String(error));
  }
}

/**
 * Match candidates against job title and requirements.
 * @param {string} jobTitle - Title of the job
 * @param {string} requirements - Raw job description or skills text
 * @param {Array<string>} candidateIds - Optional list of specific candidate IDs to match
 * @returns {Promise<Array>} Array of candidates with matchResult objects
 */
export async function matchCandidates(jobTitle, requirements, candidateIds = []) {
  if (!requirements || !requirements.trim()) {
    throw new Error('Job requirements cannot be empty.');
  }

  try {
    const response = await fetch(`${API_BASE}/match`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Accept': 'application/json',
      },
      body: JSON.stringify({
        jobTitle: jobTitle || '',
        requirements: requirements.trim(),
        candidateIds,
      }),
    });

    if (!response.ok) {
      let errorMessage = `Failed to match candidates (Status: ${response.status})`;
      try {
        const errorData = await response.json();
        if (errorData?.message || errorData?.error) errorMessage = errorData.message || errorData.error;
      } catch (_) {
        if (response.statusText) errorMessage += `: ${response.statusText}`;
      }
      throw new Error(errorMessage);
    }

    const data = await parseResponse(response);
    const candidates = Array.isArray(data) ? data : (data.candidates || []);
    return candidates.map(transformCandidate);
  } catch (error) {
    console.error('matchCandidates error:', error);
    throw error instanceof Error ? error : new Error(String(error));
  }
}

